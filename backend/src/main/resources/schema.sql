CREATE TABLE IF NOT EXISTS emergencies (
    emergency_id VARCHAR(100) PRIMARY KEY,
    tracking_token VARCHAR(120),
    emergency_type VARCHAR(60) NOT NULL,
    priority VARCHAR(24) NOT NULL,
    status VARCHAR(32) NOT NULL,
    location VARCHAR(1000),
    description VARCHAR(4000),
    phone VARCHAR(64),
    assigned_team VARCHAR(200),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    critical BOOLEAN NOT NULL DEFAULT FALSE,
    location_unavailable BOOLEAN NOT NULL DEFAULT FALSE,
    people_needing_help INT NOT NULL DEFAULT 1,
    image_data BYTEA,
    image_content_type VARCHAR(100),
    estimated_arrival VARCHAR(200),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_emergencies_created_at ON emergencies(created_at);
CREATE INDEX IF NOT EXISTS idx_emergencies_status ON emergencies(status);
