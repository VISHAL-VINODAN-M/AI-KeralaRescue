UPDATE emergencies SET status = 'RECEIVED' WHERE UPPER(status) = 'REQUESTED';
UPDATE emergencies SET status = 'UNDER REVIEW' WHERE UPPER(status) = 'ACKNOWLEDGED';
UPDATE emergencies SET status = 'HELPER ASSIGNED' WHERE UPPER(status) = 'TEAM_ASSIGNED';
UPDATE emergencies SET status = 'RESCUE IN PROGRESS' WHERE UPPER(status) = 'IN_PROGRESS';
UPDATE emergencies SET priority = 'HIGH' WHERE UPPER(priority) NOT IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW');

CREATE TABLE IF NOT EXISTS emergency_history AS SELECT * FROM emergencies WHERE 1 = 0;
CREATE UNIQUE INDEX IF NOT EXISTS idx_history_emergency_id ON emergency_history(emergency_id);

CREATE TABLE IF NOT EXISTS emergency_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emergency_id VARCHAR(100) NOT NULL,
    sender_role VARCHAR(24) NOT NULL,
    sender_name VARCHAR(120) NOT NULL,
    message_text VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_messages_emergency_created ON emergency_messages(emergency_id, created_at);

CREATE TABLE IF NOT EXISTS helpers (
